"""Generate Ytosk/lean/Ytosk/V3SeedVF.lean: the QVSF/QFO/QFCo seed producers (V3T2SeedFr, V3T2SeedFr2) on the V3
context, by the same text transformation as tmp/codex/make_seedpf_20261105.py (R : Res3W -> Ctx : StepCtx3,
callees renamed to their V3 versions in V3SeedPF, residual structures renamed to the read-only V3 ones)."""
from pathlib import Path
import re
D = Path('/home/koteitan/proofs/trio/Ytosk/lean/Ytosk')
P = D / 'V3SeedVF.lean'
assert not P.exists()


def extract(file, name, kind='theorem'):
    s = (D / (file + '.lean')).read_text(); start = s.index(kind + ' ' + name + ' ')
    m = re.search(r'\n(?:/--|theorem |end(?: |\n)|namespace |open |def |structure )', s[start + 1:])
    return s[start:start + 1 + m.start()].rstrip() + '\n' if m else s[start:]


header = '''/- QVSF/QFO/QFCo seed producers on the consistent V3 context (generated by tmp/claude/make_seedvf.py). -/
import Ytosk.V3SeedPF
import Ytosk.V3T2SeedFr
import Ytosk.V3T2SeedFr2

namespace Ytosk.V3Main.SeedPF
open T Classical WfExQ1 WfExQ2 G
set_option linter.unusedVariables false
set_option linter.unusedSectionVars false

'''
old_v3 = ['o_r_level_qr', 'seed_r_value_qr', 'qn_frame', 'o_r_level_qn', 'seed_r_value_qn', 'sv_frame', 'o_r_level_sv',
          'seed_r_value_sv', 'C_frame', 'o_r_level_C', 'seed_r_value_C', 'seed_frame_data_qr', 'seed_frame_data_qn',
          'seed_frame_data_sv', 'qn_take_t1', 't2SeedQNFC_holds', 't2SeedSVFix_holds', 't2SeedCFix_of']
seq = [('V3T2SeedFr', 'seed_last_qr'), ('V3T2SeedFr', 'seed_frames_qr3'), ('V3T2SeedFr', 'seed_last_qn'),
       ('V3T2SeedFr', 'seed_frames_qn3'), ('V3T2SeedFr2', 'seed_frames_sv3'), ('V3T2SeedFr2', 'seed_last_C'),
       ('V3T2SeedFr2', 'seed_frames_C3')]
renames = {name: name + 'V3' for name in old_v3}
renames.update({name: name + 'V3' for _, name in seq})
parts = []
for file, name in seq:
    s = extract(file, name)
    s = s.replace('(R : Res3W M ρ rk)', '(Ctx : StepCtx3 M ρ rk)').replace('I R ', 'I Ctx ')
    s = s.replace('t2CopyResAll_holds M ρ rk hM hS I Ctx', 't2CopyResV3 hM hS I')
    s = s.replace('(hch k).2.1', '(hch k).2').replace('(hch (n - 2)).2.1', '(hch (n - 2)).2')
    for a, b in renames.items():
        s = re.sub(r'\bG\.' + a + r'\b', b, s)
        s = re.sub(r'(?<![\w.])' + a + r'\b', b, s)
    for a, b in [('T2SeedQRRes', 'QRRel'), ('T2SeedQNRes', 'QNRel'), ('T2SeedSVRes', 'SVRel'), ('T2SeedCRes', 'CRel')]:
        s = s.replace(a, b)
    parts.append(s)
P.write_text(header + '\n'.join(parts) + '\nend Ytosk.V3Main.SeedPF\n')
print('wrote', P, sum(p.count('\n') for p in parts), 'lines')
