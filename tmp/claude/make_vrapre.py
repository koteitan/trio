"""Generate Ytosk/lean/Ytosk/V3VRAPreU.lean: T2VRAPre on the V3/U context, from T2SeedPreShapeC.
Copies (text transformation) of qr_frame_pre, qn_frame_pre, t2SeedPreShape_of (V3T2SeedPre: the Res3W argument R is
unused, it is dropped), t2SeedPreShapeSVC_ofXR, t2VRAPre_ofXR (WfT2R1: R -> Ctx : StepCtx3, the X readers -> U
readers), plus hand-written sv_children_ctxV3 and t2SVc0'_of_dropV3."""
from pathlib import Path
import re
D = Path('/home/koteitan/proofs/trio/Ytosk/lean/Ytosk')
P = D / 'V3VRAPreU.lean'
assert not P.exists()


def extract(file, name, kind='theorem'):
    s = (D / (file + '.lean')).read_text(); start = s.index(kind + ' ' + name + ' ')
    m = re.search(r'\n(?:/--|theorem |end(?: |\n)|namespace |open |def |structure |set_option )', s[start + 1:])
    return s[start:start + 1 + m.start()].rstrip() + '\n' if m else s[start:]


def noR(s):
    s = s.replace(' (R : Res3W M ρ rk)', '')
    s = s.replace('hM hS I R ', 'hM hS I ')
    return s


X = '(fun h => hz ((col_zero_iff M _).mpr h))'
GOOD_OLD = ('good3_expand_t2 hM hS I R hz h2 (WfT2X.t2BelowXE_ofX hB hM hS I R hz h2)\n'
            '    (t2CopyResAll_holds M ρ rk hM hS I R hz h2)')
GOOD_NEW = ('good3_expand_t2V3 hM hS I (Ctx.drop (len2_of_t2 Ctx hz h2)) hz h2\n'
            '    (t2BelowXE_V3U hB hM hS I (Ctx.drop (len2_of_t2 Ctx hz h2)) hz h2) (t2CopyResV3 hM hS I hz h2)')


def toU(s, name):
    s = s.replace('(hB : WfT2X.T2BelowXResAtX M ρ rk)', '(hB : T2BelowAtV3U M ρ)')
    s = s.replace('(R : Res3W M ρ rk)', '(Ctx : StepCtx3 M ρ rk)')
    assert GOOD_OLD in s, name
    s = s.replace(GOOD_OLD, GOOD_NEW)
    s = s.replace('WfT2X.t2BelowXS_ofX hB hM hS I R hz h2', 't2BelowXS_V3U hB hM hS I (Ctx.drop (len2_of_t2 Ctx hz h2)) hz h2')
    s = s.replace('WfAbsW.FrameShapeX ', 'WfAbsW.FrameShapeXU ')
    s = s.replace('pathLvAll_pre_t2XR ', 'pathLvAll_pre_t2XRU ')
    s = s.replace('sv_children_ctx hM hS I R ', 'sv_children_ctxV3 hM hS I Ctx ')
    s = s.replace('sv_frame hM hS I R ', 'sv_frameV3 hM hS I Ctx ')
    s = s.replace('t2SeedPreShapeSVC_ofXR', 't2SeedPreShapeSVC_ofV3U').replace('t2VRAPre_ofXR', 't2VRAPre_ofV3U')
    assert ' R ' not in s.replace("R' ", '').replace('(R :', ''), name
    return s


header = '''/-
**T2VRAPre on the V3/U context (2026-11-06, generated by tmp/claude/make_vrapre.py).**

`T2VRAPre` (a residual of `hN_of2`: the path levels of `M[n]` before `x`, away from the seed columns, are levels of
`M`) from the C part `T2SeedPreShapeC` of the seed frame shape:
- `t2VRAPre_ofV3U`: `T2VRAPre ⟸ T2SeedPreShape` (the frame shape `FrameShapeXU` of `T2BelowAtV3U` at the other columns,
  `pathLvAll_pre_t2XRU`).
- `t2SeedPreShape_ofV3`: `T2SeedPreShape ⟸ T2SeedPreShapeSVC` (qr, qn proved; copies of V3T2SeedPre without the unused
  `Res3W`).
- `t2SeedPreShapeSVC_ofV3U`: the sv part from `T2SVc0` (`t2SVc0'_of_dropV3`: the drop lemma's PO of `DropV3`).
-/
import Ytosk.V3SeedPF
import Ytosk.V3T2VRAPre
import Ytosk.V3T2SeedPre
import Ytosk.V3T2VRASV
import Ytosk.WfT2R1U
import Ytosk.V3T2BelowV3U
import Ytosk.V3T2GoodV3
import Ytosk.V3T2CopyV3
import Ytosk.V3T2SmallV3U

namespace Ytosk.V3Main.SeedPF
open T Classical WfExQ1 WfExQ2 G
set_option linter.unusedVariables false
set_option linter.unusedSectionVars false

'''
hand = (Path('/home/koteitan/proofs/trio/tmp/claude/vrapre_hand.lean')).read_text()
parts = []
for name in ['qr_frame_pre', 'qn_frame_pre']:
    s = noR(extract('V3T2SeedPre', name)).replace('theorem ' + name + ' ', 'theorem ' + name + 'V3 ')
    parts.append(s)
s = noR(extract('V3T2SeedPre', 't2SeedPreShape_of')).replace('theorem t2SeedPreShape_of ', 'theorem t2SeedPreShape_ofV3 ')
s = s.replace('qr_frame_pre ', 'qr_frame_preV3 ').replace('qn_frame_pre ', 'qn_frame_preV3 ')
parts.append(s)
parts.append(hand)
for name in ['t2SeedPreShapeSVC_ofXR', 't2VRAPre_ofXR']:
    parts.append(toU(extract('WfT2R1', name), name))
final = '''
/-- **`T2VRAPre` from the C part `T2SeedPreShapeC`** of the seed frame shape (the sv part `T2SVc0` is proved). -/
theorem t2VRAPre_ofC {M : Mat} {ρ : Valn} {rk : Bool → Nat → Nat} (hB : T2BelowAtV3U M ρ)
    (hM : Std M) (hS : M ≠ SRO) (I : Inv3W M ρ rk) (Ctx : StepCtx3 M ρ rk)
    (hz : col M (M.length - 1) ≠ (0, 0, 0)) (h2 : TRIO.srow M (M.length - 1) = 2)
    (hC : T2SeedPreShapeC M ρ) : T2VRAPre M ρ :=
  t2VRAPre_ofV3U hB hM hS I Ctx hz h2 (t2SeedPreShape_ofV3 hM hS I hz h2
    (t2SeedPreShapeSVC_ofV3U hB hM hS I Ctx hz h2 (fun r L hlen hr _ => t2SVc0_ofV3 I Ctx hlen hr) hC))

#print axioms t2VRAPre_ofC
'''
P.write_text(header + '\n'.join(parts) + final + '\nend Ytosk.V3Main.SeedPF\n')
print('wrote', P, sum(p.count('\n') for p in parts), 'lines')
