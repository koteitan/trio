"""Generate Ytosk/lean/Ytosk/V3SeedDecV3.lean: seed_dec_*, seed_ot_*, seedL_* (qr, qn, sv, C) on the V3 context, by the
transformation of make_seedvf.py (R : Res3W -> Ctx : StepCtx3, callees to their V3SeedPF versions, residual structures
renamed to the read-only V3 ones)."""
from pathlib import Path
import re
D = Path('/home/koteitan/proofs/trio/Ytosk/lean/Ytosk')
P = D / 'V3SeedDecV3.lean'


def extract(file, name, kind='theorem'):
    s = (D / (file + '.lean')).read_text(); start = s.index(kind + ' ' + name + ' ')
    m = re.search(r'\n(?:/--|theorem |end(?: |\n)|namespace |open |def |structure |#print|section)', s[start + 1:])
    return s[start:start + 1 + m.start()].rstrip() + '\n' if m else s[start:]


header = '''/- seed_dec / seed_ot / seedL (qr, qn, sv, C) on the consistent V3 context (generated by tmp/claude/make_seeddec.py). -/
import Ytosk.V3T2BelowNarrow
import Ytosk.V3T2SeedQR
import Ytosk.V3T2SeedQN
import Ytosk.V3T2SeedSV
import Ytosk.V3T2SeedC
import Ytosk.V3T2SeedOT
import Ytosk.V3T2SeedQRL
import Ytosk.V3T2SeedQNV

namespace Ytosk.V3Main.SeedPF
open T Classical WfExQ1 WfExQ2 G
set_option linter.unusedVariables false
set_option linter.unusedSectionVars false

'''
old_v3 = ['o_r_level_qr', 'seed_r_value_qr', 'qn_frame', 'o_r_level_qn', 'seed_r_value_qn', 'sv_frame', 'o_r_level_sv',
          'seed_r_value_sv', 'C_frame', 'o_r_level_C', 'seed_r_value_C', 'seed_frame_data_qr', 'seed_frame_data_qn',
          'seed_frame_data_sv']
seq = [('V3T2SeedQR', 'seed_dec_qr'), ('V3T2SeedQN', 'seed_dec_qn'), ('V3T2SeedSV', 'seed_dec_sv'), ('V3T2SeedC', 'seed_dec_C'),
       ('V3T2SeedOT', 'seed_ot_qr'), ('V3T2SeedOT', 'seed_ot_qn'), ('V3T2SeedOT', 'seed_ot_sv'), ('V3T2SeedOT', 'seed_ot_C'),
       ('V3T2SeedQRL', 'seedL_qr'), ('V3T2SeedQNV', 'seedL_qn'), ('V3T2SeedSV', 'seedL_sv'), ('V3T2SeedC', 'seedL_C')]
renames = {name: name + 'V3' for name in old_v3}
renames.update({name: name + 'V3' for _, name in seq})
parts = []
for file, name in seq:
    s = extract(file, name)
    s = s.replace('(R : Res3W M ρ rk)', '(Ctx : StepCtx3 M ρ rk)').replace('I R ', 'I Ctx ')
    s = s.replace('t2CopyResAll_holds M ρ rk hM hS I Ctx', 't2CopyResV3 hM hS I')
    for a, b in renames.items():
        s = re.sub(r'\bG\.' + a + r'\b', b, s)
        s = re.sub(r'(?<![\w.])' + a + r'\b', b, s)
    for a, b in [('T2SeedQRRes', 'QRRel'), ('T2SeedQNRes', 'QNRel'), ('T2SeedSVRes', 'SVRel'), ('T2SeedCRes', 'CRel')]:
        s = s.replace(a, b)
    parts.append(s)
P.write_text(header + '\n'.join(parts) + '\nend Ytosk.V3Main.SeedPF\n')
print('wrote', P, sum(p.count('\n') for p in parts), 'lines')
